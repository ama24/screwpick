"""Regenerate requirements-pi.lock.txt: every package the Pi needs, exact versions and hashes.

Run on any computer with internet (it only asks pip to resolve, nothing is installed):
    python scripts/lock_pi.py
The lock is resolved for 64-bit Raspberry Pi OS (aarch64) with Python 3.11 (Bookworm) and
3.13 (Trixie); both get the same versions, and the hashes of the wheels for both are listed.
Only run this when you deliberately want newer versions; then test on the Pi before committing.
"""

from __future__ import annotations

import hashlib
import json
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PYTHONS = ("3.11", "3.13")
PLATFORMS = (
    "manylinux_2_28_aarch64",
    "manylinux2014_aarch64",
    "manylinux_2_17_aarch64",
    "linux_aarch64",
)
TORCH_INDEX = "https://download.pytorch.org/whl/cpu"
# what sortering-pnp, screwsynth (inference) and screwrig need on the Pi
TOP = [
    "opencv-contrib-python-headless",  # cv2 with ArUco; NOT opencv-python (see SKIP)
    "torch",
    "torchvision",
    "ultralytics",
    "ncnn",
    "pyserial",
    "pyyaml",
    "numpy",
    "websocket-client",
    "manifold3d",
    "simplejpeg",  # Picamera2 (apt) with numpy 2 in the venv on Bookworm
    "hatchling",  # builds the three local packages without fetching anything at install time
    "editables",
]
# ultralytics asks for opencv-python, which would overwrite opencv-contrib-python-headless
# (both provide cv2): it is left out, and the lock is installed with --no-deps
SKIP = {"opencv-python"}
# versions that exist for every Python in PYTHONS (the newest for one is not always there for all)
COMMON = ["numpy==2.4.6", "contourpy==1.3.3", "networkx==3.6.1"]


def resolve(python: str, work: Path) -> list[dict]:
    req = work / "req.in"
    req.write_text("\n".join(TOP) + "\n", encoding="utf-8")
    con = work / "common.txt"
    con.write_text("\n".join(COMMON) + "\n", encoding="utf-8")
    report = work / f"report-{python}.json"
    cmd = [sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet"]
    cmd += ["--report", str(report), "--implementation", "cp", "--python-version", python]
    cmd += ["--only-binary=:all:", "--extra-index-url", TORCH_INDEX, "-r", str(req), "-c", str(con)]
    for plat in PLATFORMS:
        cmd += ["--platform", plat]
    subprocess.run(cmd, check=True)
    return json.loads(report.read_text(encoding="utf-8"))["install"]


def _sha256(item: dict) -> str:
    info = item["download_info"]
    archive = info.get("archive_info", {})
    sha = (archive.get("hashes") or {}).get("sha256")
    if not sha and str(archive.get("hash", "")).startswith("sha256="):
        sha = archive["hash"].split("=", 1)[1]
    if not sha and "#sha256=" in info.get("url", ""):
        sha = info["url"].split("#sha256=", 1)[1]
    if not sha:  # the PyTorch mirror lists no hashes: the same file on PyPI, else hash it here
        sha = _pypi_sha256(item) or _download_sha256(info["url"])
    return sha


def _pypi_sha256(item: dict) -> str | None:
    meta = item["metadata"]
    filename = item["download_info"]["url"].rsplit("/", 1)[-1].split("#")[0]
    url = f"https://pypi.org/pypi/{meta['name']}/{meta['version']}/json"
    try:
        with urllib.request.urlopen(url, timeout=60) as r:
            files = json.loads(r.read())["urls"]
    except OSError:
        return None
    return next((f["digests"]["sha256"] for f in files if f["filename"] == filename), None)


def _download_sha256(url: str) -> str:
    h = hashlib.sha256()
    with urllib.request.urlopen(url.split("#")[0], timeout=600) as r:
        for chunk in iter(lambda: r.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main() -> int:
    pins: dict[str, str] = {}
    hashes: dict[str, set[str]] = {}
    with tempfile.TemporaryDirectory() as tmp:
        for py in PYTHONS:
            for item in resolve(py, Path(tmp)):
                name = item["metadata"]["name"].lower()
                if name in SKIP:
                    continue
                version = item["metadata"]["version"]
                if pins.setdefault(name, version) != version:
                    raise SystemExit(f"{name}: {pins[name]} vs {version} - add it to COMMON")
                hashes.setdefault(name, set()).add(_sha256(item))
    lines = [
        "# GENERATED by scripts/lock_pi.py - do not edit by hand.",
        "# Everything the Pi needs (sortering-pnp + screwsynth inference + screwrig), exact versions",
        "# and file hashes, for 64-bit Raspberry Pi OS with Python 3.11 (Bookworm) or 3.13 (Trixie).",
        "# Installed by install-pi.sh with --no-deps --require-hashes: nothing else, nothing newer.",
        f"--extra-index-url {TORCH_INDEX}",
        "",
    ]
    for name in sorted(pins):
        h = " ".join(f"--hash=sha256:{x}" for x in sorted(hashes[name]))
        lines.append(f"{name}=={pins[name]} \\\n    {h}")
    out = ROOT / "requirements-pi.lock.txt"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{out}: {len(pins)} packages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
